const agentOrder: AgentKey[] = [
  "website",
  "reviews",
  "price",
  "news",
  "social",
  "ads",
  "filings",
  "search",
];

export default function AgentRoster() {
  const { messages } = useI18n();
  const t = messages.agentRoster;
  const ref = useRef<HTMLDivElement>(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const obs = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setVisible(true);
          obs.disconnect();
        }
      },
      { threshold: 0.1 }
    );
    obs.observe(el);
    return () => obs.disconnect();
  }, []);

  return (
    <section className="bg-cream-dark px-6 py-20 lg:px-8">
      <div ref={ref} className="mx-auto max-w-4xl">
        <h2 className="flex items-center justify-center gap-2 font-heading text-2xl md:text-3xl">
          {t.title}
          <SubAgentSpawn active={visible} />
        </h2>
        <p className="mx-auto mt-3 max-w-2xl text-center text-sm text-text-muted md:text-base">
          {t.subtitle}
        </p>

        <div className="mt-12 grid gap-4 sm:grid-cols-2">
          {agentOrder.map((key, i) => {
            const agent = t.agents[key];
            return (
              <div
                key={key}
                className={`flex items-start gap-3 rounded-xl border border-border-warm bg-white p-4 transition-all duration-500 ${
                  visible
                    ? "translate-y-0 opacity-100"
                    : "translate-y-4 opacity-0"
                }`}
                style={{ transitionDelay: `${i * 70}ms` }}
              >
                <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-gold/10 text-gold-dark">
                  {agentIcons[key]}
                </div>
                <div>
                  <h3 className="text-sm font-semibold text-text-primary">
                    {agent.name}
                  </h3>
                  <p className="mt-0.5 text-xs leading-relaxed text-text-muted">
                    {agent.description}
                  </p>
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </section>
  );
}
